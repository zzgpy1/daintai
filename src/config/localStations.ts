/**
 * 解析原始数据，生成 RadioStation 数组（去重）
 */
function parseLocalStations(): RadioStation[] {
  const lines = rawData.trim().split('\n').filter(line => line.trim())
  const seenUrls = new Set<string>()
  const stations: RadioStation[] = []

  for (const line of lines) {
    const parts = line.split(',').map(s => s.trim())
    if (parts.length < 2) continue
    const name = parts[0]
    const url = parts[1]
    if (!url || seenUrls.has(url)) continue
    seenUrls.add(url)

    // 尝试从名称推断标签（简单启发）
    let tags = ''
    if (name.includes('音乐') || name.includes('Music') || name.includes('FM')) tags += 'music,'
    if (name.includes('新闻') || name.includes('News')) tags += 'news,'
    if (name.includes('交通') || name.includes('Traffic')) tags += 'traffic,'
    if (name.includes('文艺') || name.includes('文化')) tags += 'culture,'
    if (name.includes('经济') || name.includes('财经')) tags += 'economy,'
    if (name.includes('体育') || name.includes('Sport')) tags += 'sports,'
    if (name.includes('故事') || name.includes('评书')) tags += 'story,'
    if (name.includes('生活')) tags += 'life,'
    if (name.includes('乡村') || name.includes('农村')) tags += 'countryside,'
    if (name.includes('教育')) tags += 'education,'
    if (name.includes('蒙古') || name.includes('藏语') || name.includes('朝鲜语')) tags += 'ethnic,'
    tags = tags.replace(/,$/, '')

    stations.push({
      stationuuid: `local_${url.replace(/[^a-zA-Z0-9]/g, '_')}`,
      name,
      url,
      url_resolved: url,
      homepage: '',
      favicon: '',
      tags,
      country: 'China',
      countrycode: 'CN',
      state: '',
      language: 'Chinese',
      languagecodes: 'zh',
      votes: 0,
      codec: 'm3u8',
      bitrate: 0,
      hls: 1, // 标记为 HLS 流，以便播放器特殊处理（可选）
      lastcheckok: 1,
      clickcount: 0,
      clicktrend: 0,
      geo_lat: null,
      geo_long: null,
    })
  }
  return stations
}

